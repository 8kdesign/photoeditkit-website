// Pre-generates resized AVIF copies of public/examples/*.jpg and a tiny blur placeholder for each,
// so the site serves static files instead of resizing images on the server.
// Runs automatically before `npm run build`; run `npm run images` after adding or replacing a photo.
import { readdir, mkdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "public/examples");
const outDir = path.join(srcDir, "opt");
const blurFile = path.join(root, "lib/blur-data.ts");

// Keep in sync with WIDTHS in components/ExampleImage.tsx. 160 covers the 80px hero thumbnails at 2x,
// 640 the recipe cards and phones at 1x, 1200 the hero slider on retina screens.
const WIDTHS = [160, 640, 1200];
// Matches what Next's image optimizer produces at its default quality 75.
const AVIF = { quality: 50, effort: 4, chromaSubsampling: "4:2:0" };

const isNewer = async (file, than) => {
  try {
    return (await stat(file)).mtimeMs >= than;
  } catch {
    return false;
  }
};

await mkdir(outDir, { recursive: true });
const files = (await readdir(srcDir)).filter((f) => f.endsWith(".jpg")).sort();
const blur = {};
let written = 0;

for (const file of files) {
  const src = path.join(srcDir, file);
  const base = file.replace(/\.jpg$/, "");
  const srcTime = (await stat(src)).mtimeMs;
  for (const w of WIDTHS) {
    const out = path.join(outDir, `${base}-${w}.avif`);
    if (await isNewer(out, srcTime)) continue;
    await sharp(src).rotate().resize({ width: w, withoutEnlargement: true }).avif(AVIF).toFile(out);
    written++;
  }
  const tiny = await sharp(src).rotate().resize(10, 10, { fit: "inside" }).webp({ quality: 50 }).toBuffer();
  blur[`/examples/${file}`] = `data:image/webp;base64,${tiny.toString("base64")}`;
}

const body =
  "// Generated by scripts/optimize-images.mjs. Do not edit by hand.\n" +
  "export const blurData: Record<string, string> = " +
  JSON.stringify(blur, null, 2) +
  ";\n";
await writeFile(blurFile, body);
console.log(`optimize-images: ${files.length} photos, ${written} files written, blur placeholders updated`);
